def get_article(article_id):
    """按编号查询法条，不存在时返回 None。"""
    return REGULATIONS.get(article_id)


def format_article(article_id):
    """把法条格式化为「《法规名》第X条：摘要」的展示字符串。"""
    item = REGULATIONS.get(article_id)
    if not item:
        return article_id
    return f"{item['law']}{item['article']}：{item['summary']}"
